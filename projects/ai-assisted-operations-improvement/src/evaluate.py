"""Compute the simulated baseline and evaluate the rules baseline.

Reads data/synthetic/*.csv and writes:
- reports/baseline-report.md      (simulated current state)
- reports/rules-evaluation.md     (rules baseline on dev and held-out splits)
- reports/effort-scenarios.md     (expected-benefit scenarios; assumptions only)

Every number in these reports comes from SYNTHETIC data or from stated
assumptions. None is a measurement of a real organisation.

Run:  python src/evaluate.py
"""
from __future__ import annotations

import csv
import datetime as dt
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

from triage_rules import CATEGORIES, SENSITIVE, classify, missing_fields, route

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "synthetic"
REPORTS = ROOT / "reports"
DEV_WEEKS = range(1, 7)
BANNER = ("> **Synthetic data.** Generated by `src/generate_data.py` (fixed seed). "
          "These figures demonstrate the method; they are not measurements of any real organisation.\n")


def load():
    with open(DATA / "requests.csv", encoding="utf-8") as fh:
        reqs = list(csv.DictReader(fh))
    with open(DATA / "events.csv", encoding="utf-8") as fh:
        events = list(csv.DictReader(fh))
    for r in reqs:
        r["week"] = int(r["week"])
    return reqs, events


def pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "n/a"


def q(values, p):
    values = sorted(values)
    if not values:
        return float("nan")
    k = (len(values) - 1) * p
    lo, hi = int(k), min(int(k) + 1, len(values) - 1)
    return values[lo] + (values[hi] - values[lo]) * (k - lo)


def baseline(reqs, events) -> dict:
    by_req = defaultdict(dict)
    for e in events:
        by_req[e["request_id"]][e["event"]] = dt.datetime.strptime(e["timestamp"], "%Y-%m-%d %H:%M")
    hours = lambda a, b: (b - a).total_seconds() / 3600
    first, resolve, safety_first = [], [], []
    handoffs = followups = 0
    for r in reqs:
        ev = by_req[r["request_id"]]
        ft = hours(ev["received"], ev["first_touch"])
        first.append(ft)
        resolve.append(hours(ev["received"], ev["resolved"]))
        if r["true_category"] == "SAFETY_SECURITY":
            safety_first.append(ft)
        handoffs += "handoff" in ev
        followups += "info_requested" in ev
    n = len(reqs)
    weeks = max(r["week"] for r in reqs)
    triage_min, followup_min = 4.0, 6.0  # from generate_data.ASSUMPTIONS
    effort_h = (n * triage_min + followups * followup_min) / 60
    return {
        "n": n, "weeks": weeks,
        "first_median": st.median(first), "first_p90": q(first, 0.9),
        "resolve_median": st.median(resolve), "resolve_p90": q(resolve, 0.9),
        "handoff_rate": handoffs / n, "followup_rate": followups / n,
        "safety_first_median": st.median(safety_first), "safety_first_max": max(safety_first),
        "safety_over_2h": sum(x > 2 for x in safety_first), "safety_n": len(safety_first),
        "effort_h": effort_h, "effort_h_week": effort_h / weeks,
    }


def eval_rules(split):
    n = len(split)
    answered = correct = 0
    by_style = defaultdict(lambda: [0, 0, 0])  # n, answered, correct
    confusion = Counter()
    lanes = Counter()
    auto_wrong = []
    strict_auto = strict_wrong = 0  # policy B: AUTO only when a web-form category confirms the rules
    sens_total = sens_protected = nonsens_protected = 0
    miss_tp = miss_fp = miss_fn = miss_tn = 0
    for r in split:
        cat, _ = classify(r)
        s = by_style[r["style"]]
        s[0] += 1
        if cat is not None:
            answered += 1
            s[1] += 1
            confusion[(r["true_category"], cat)] += 1
            if cat == r["true_category"]:
                correct += 1
                s[2] += 1
        else:
            confusion[(r["true_category"], "ABSTAIN")] += 1
        d = route(r)
        lanes[d["lane"]] += 1
        if d["lane"] == "AUTO" and d["category"] != r["true_category"]:
            auto_wrong.append(r)
        if d["lane"] == "AUTO" and r["form_category"] == d["category"]:
            strict_auto += 1
            strict_wrong += d["category"] != r["true_category"]
        if r["true_category"] in SENSITIVE:
            sens_total += 1
            sens_protected += d["lane"] == "PROTECTED"
        elif d["lane"] == "PROTECTED":
            nonsens_protected += 1
        truth = bool(r["missing_fields"])
        pred = bool(missing_fields(r, r["true_category"]))
        miss_tp += truth and pred
        miss_fp += (not truth) and pred
        miss_fn += truth and not pred
        miss_tn += (not truth) and not pred
    return dict(n=n, answered=answered, correct=correct, by_style=dict(by_style), confusion=confusion,
                lanes=lanes, auto_wrong=auto_wrong, sens_total=sens_total, sens_protected=sens_protected,
                nonsens_protected=nonsens_protected, strict_auto=strict_auto, strict_wrong=strict_wrong, miss=(miss_tp, miss_fp, miss_fn, miss_tn))


def delay_shares(events):
    by_req = defaultdict(list)
    for e in events:
        by_req[e["request_id"]].append((e["event"], dt.datetime.strptime(e["timestamp"], "%Y-%m-%d %H:%M")))
    totals = Counter()
    for evs in by_req.values():
        for (_, t1), (stage, t2) in zip(evs, evs[1:]):
            totals[stage] += (t2 - t1).total_seconds() / 3600
    whole = sum(totals.values())
    return {k: 100 * totals[k] / whole for k in ("resolved", "first_touch", "info_received", "handoff")}


def write_baseline(b):
    md = ["# Simulated current-state baseline\n", BANNER,
          "\nThe event log is produced from the assumptions listed in "
          "[docs/03-baseline-and-data.md](../docs/03-baseline-and-data.md). "
          "The value of this report is the **measurement method**: the same calculations would run on a real export of a mailbox or ticket system.\n",
          "\n| Measure | Simulated value | Definition |\n|---|---|---|",
          f"| Requests | {b['n']} over {b['weeks']} weeks | Rows in requests.csv |",
          f"| Time to first touch, median | {b['first_median']:.1f} h | received → first coordinator action |",
          f"| Time to first touch, 90th percentile | {b['first_p90']:.1f} h | as above |",
          f"| Time to resolution, median | {b['resolve_median']:.1f} h | received → resolved (calendar hours) |",
          f"| Time to resolution, 90th percentile | {b['resolve_p90']:.1f} h | as above |",
          f"| Requests handed off at least once | {100 * b['handoff_rate']:.1f}% | a `handoff` event exists |",
          f"| Requests needing an information follow-up | {100 * b['followup_rate']:.1f}% | an `info_requested` event exists |",
          f"| Safety requests: median time to first touch | {b['safety_first_median']:.1f} h | safety category only |",
          f"| Safety requests first touched after more than 2 h | {b['safety_over_2h']} of {b['safety_n']} | the risk the redesign must remove |",
          f"| Coordinator triage and follow-up effort | {b['effort_h']:.0f} h total, about {b['effort_h_week']:.1f} h per week | 4 min per request + 6 min per follow-up (assumptions) |",
          "\n## Where the elapsed time goes\n",
          "Each interval between consecutive events is attributed to the stage it ends. Calendar hours, summed over all requests.\n",
          "| Stage | Share of elapsed time | Addressed by the redesign? |\n|---|---|---|",
          f"| Handler work (last step before resolution) | {b['share']['resolved']:.0f}% | No: outside the scope of intake and triage |",
          f"| Waiting for first touch | {b['share']['first_touch']:.0f}% | Yes: triage order, protected lane, AUTO routing |",
          f"| Waiting for the requester to supply missing information | {b['share']['info_received']:.0f}% | Yes: required-field form, completeness check |",
          f"| Handoffs between queues | {b['share']['handoff']:.0f}% | Yes: better routing, one request per submission |",
          "\n## How to read this\n",
          "- Most elapsed time is handlers doing the work. Intake and triage changes cannot shorten that, so claims about end-to-end speed must be modest.",
          "- Of the time the redesign can influence, waiting for first touch and waiting for missing information are the largest parts. Neither needs AI to improve.",
          "- The safety figure is the most important row. In the current design, an urgent request waits in the same inbox as a stationery order.",
          ]
    (REPORTS / "baseline-report.md").write_text("\n".join(md) + "\n", encoding="utf-8")


def write_rules(dev, test):
    def block(name, e):
        tp, fp, fn, tn = e["miss"]
        rows = [f"\n## {name}: {e['n']} requests\n",
                "| Measure | Value |\n|---|---|",
                f"| Rules gave an answer (coverage) | {pct(e['answered'], e['n'])} |",
                f"| Correct when an answer was given | {pct(e['correct'], e['answered'])} |",
                f"| Lane AUTO / REVIEW / PROTECTED | {e['lanes']['AUTO']} / {e['lanes']['REVIEW']} / {e['lanes']['PROTECTED']} |",
                f"| Wrong queue in the AUTO lane (silent misroutes) | {len(e['auto_wrong'])} of {e['lanes']['AUTO']} ({pct(len(e['auto_wrong']), e['lanes']['AUTO'])}) |",
                f"| Policy B (AUTO only when the web-form category agrees): AUTO requests | {e['strict_auto']} of {e['n']} |",
                f"| Policy B: wrong queue in the AUTO lane | {e['strict_wrong']} of {e['strict_auto']} ({pct(e['strict_wrong'], e['strict_auto'])}) |",
                f"| Sensitive requests sent to PROTECTED | {e['sens_protected']} of {e['sens_total']} |",
                f"| Non-sensitive requests sent to PROTECTED (false alarms) | {e['nonsens_protected']} |",
                f"| Missing-information check: precision | {pct(tp, tp + fp)} |",
                f"| Missing-information check: recall | {pct(tp, tp + fn)} |",
                "\n| Writing style | Requests | Coverage | Correct when answered |\n|---|---|---|---|"]
        for style in ("clear", "indirect", "trap"):
            n, a, c = e["by_style"].get(style, [0, 0, 0])
            rows.append(f"| {style} | {n} | {pct(a, n)} | {pct(c, a)} |")
        return rows

    md = ["# Rules baseline evaluation\n", BANNER,
          "\nThe rules in `src/triage_rules.py` were written by reading the development split only. "
          "The held-out split was not used to change them. Because the same author wrote the data generator and the rules, "
          "even the held-out figure is optimistic and says nothing about real-world accuracy.\n"]
    md += block("Development split (weeks 1-6)", dev)
    md += block("Held-out split (weeks 7-12)", test)
    md += ["\n## Held-out confusion (true category → rules answer)\n",
           "| True \\ Rules | " + " | ".join(c[:6] for c in CATEGORIES) + " | ABSTAIN |",
           "|---|" + "---|" * (len(CATEGORIES) + 1)]
    for t in CATEGORIES:
        md.append(f"| {t} | " + " | ".join(str(test['confusion'][(t, p)]) for p in CATEGORIES + ['ABSTAIN']) + " |")
    md += ["\n## Silent misroutes on the held-out split\n",
           "These are the costly errors: the request goes to the wrong queue and nobody is told.\n",
           "| Request | True | Rules | Style | Two requests in one message | Subject |\n|---|---|---|---|---|---|"]
    for r in test["auto_wrong"]:
        md.append(f"| {r['request_id']} | {r['true_category']} | {classify(r)[0]} | {r['style']} | "
                  f"{'yes' if r['multi_intent'] == '1' else 'no'} | {r['subject']} |")
    md += ["\n## Limits of these figures\n",
           "- **Missing-information recall is partly circular.** The check looks for the exact formats the generator uses, so it cannot miss a field the generator left out. "
           "The precision figure is more informative: when a requester writes a field informally, the check asks for information that was already given.",
           "- **The missing-information check is scored with the true category.** In use it would run on the category the rules or a coordinator chose, so routing errors would add further mistakes.",
           "- **Policy B's result depends on an assumption.** In the generator, a wrong web-form category is chosen at random, independently of the message text. "
           "Real requesters may choose the wrong category for the same reason the rules do (misleading keywords). Errors would then agree, and Policy B would misroute more often than shown here.",
           "- **Sensitive-request protection is partly circular.** The protected-hint list was written with knowledge of the generator's vocabulary. Real messages will contain phrasing the list does not cover.",
           ]
    (REPORTS / "rules-evaluation.md").write_text("\n".join(md) + "\n", encoding="utf-8")


def write_scenarios(test, b):
    lanes = test["lanes"]
    n = test["n"]
    prot = lanes["PROTECTED"]
    # Assumptions (minutes of coordinator time per request), stated in the report
    manual, auto_check, review_with_accepted_ai = 4.0, 0.5, 1.5

    def minutes(auto, review, accept=0.0):
        return auto * auto_check + prot * manual + review * (accept * review_with_accepted_ai + (1 - accept) * manual)

    current = n * manual
    a_auto, a_review = lanes["AUTO"], lanes["REVIEW"]
    b_auto = test["strict_auto"]
    b_review = n - b_auto - prot
    rows = [("Current: everything triaged by hand", current, "—"),
            ("Policy A: rules decide alone (not recommended)", minutes(a_auto, a_review),
             f"{len(test['auto_wrong'])} silent misroutes"),
            ("Policy B: rules + web-form agreement, no AI", minutes(b_auto, b_review),
             f"{test['strict_wrong']} silent misroutes")]
    for acc in (0.4, 0.6, 0.8):
        rows.append((f"Policy B + AI suggestions, {int(acc * 100)}% accepted", minutes(b_auto, b_review, acc),
                     "unknown: accepted-but-wrong rate not measured"))
    md = ["# Effort scenarios (expected benefit, not results)\n", BANNER,
          "\nThis is a **scenario model**. It combines lane counts from the held-out rules evaluation with assumed handling times. "
          "It shows what would have to be true for the redesign to be worth it, and which assumption matters most. "
          "No AI model was run, so the AI rows depend entirely on an assumed acceptance rate.\n",
          "\n| Assumption | Value |\n|---|---|",
          f"| Manual triage, per request | {manual} min |",
          f"| Spot-check of an AUTO-routed request | {auto_check} min |",
          f"| REVIEW with an AI suggestion the coordinator accepts | {review_with_accepted_ai} min |",
          f"| REVIEW without a usable suggestion | {manual} min |",
          "| PROTECTED requests | always manual |",
          f"\nHeld-out split: {n} requests, of which {prot} PROTECTED.\n",
          "| Scenario | Triage minutes | Change vs current | Error exposure |\n|---|---|---|---|"]
    for name, m, risk in rows:
        change = "—" if name.startswith("Current") else f"{100 * (m - current) / current:+.0f}%"
        md.append(f"| {name} | {m:.0f} | {change} | {risk} |")
    md += ["\n## Reading the scenarios\n",
           "- Policy A saves the most time on paper but sends requests to the wrong queue without telling anyone. That is a worse outcome than a slow, correct one.",
           "- Policy B is slower but, on this data, made no silent misroutes. The saving comes from structured intake, not from AI.",
           "- AI only acts on the REVIEW lane. Its value depends on two numbers a pilot must measure: how often coordinators accept the suggestion, and how often an accepted suggestion turns out to be wrong.",
           "- Triage effort is a small part of the picture: about four hours a week in the simulated baseline. The waiting time before first touch and for missing information affects requesters more, and the intake form and protected lane address those without AI."]
    (REPORTS / "effort-scenarios.md").write_text("\n".join(md) + "\n", encoding="utf-8")


def main():
    reqs, events = load()
    REPORTS.mkdir(exist_ok=True)
    dev = [r for r in reqs if r["week"] in DEV_WEEKS]
    test = [r for r in reqs if r["week"] not in DEV_WEEKS]
    b = baseline(reqs, events)
    b["share"] = delay_shares(events)
    e_dev, e_test = eval_rules(dev), eval_rules(test)
    write_baseline(b)
    write_rules(e_dev, e_test)
    write_scenarios(e_test, b)
    print("held-out:", {k: e_test[k] for k in ("n", "answered", "correct", "sens_total", "sens_protected", "nonsens_protected")},
          dict(e_test["lanes"]), "auto_wrong", len(e_test["auto_wrong"]), "miss", e_test["miss"])
    print("dev:", {k: e_dev[k] for k in ("n", "answered", "correct")}, dict(e_dev["lanes"]), len(e_dev["auto_wrong"]))


if __name__ == "__main__":
    main()
